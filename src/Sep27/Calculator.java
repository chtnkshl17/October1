package Sep27;

public class Calculator {

    public double sum(double a,double b){
        double sum = a + b;
        return sum;
    }

    public double sub(double a, double b){
        double sub = a - b;
        return sub;
    }

    public double mul(double a, double b){
        double mul = a * b;
        return mul;
    }

    public double div(double a,double b){
        double div = a / b;
        return div;
    }
}
